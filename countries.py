COUNTRY_NAMES = sorted(set(COUNTRY_MAP.values()), key=len, reverse=True)

def normalise_country(raw):
    """Return a consistent country name from a WatchMeFly country/code value."""
    raw = str(raw or "").strip()
    if not raw:
        return ""
    if raw in COUNTRY_MAP:
        return COUNTRY_MAP[raw]
    upper = raw.upper()
    if upper in COUNTRY_MAP:
        return COUNTRY_MAP[upper]
    folded = raw.casefold()
    for key, value in COUNTRY_MAP.items():
        if key.casefold() == folded:
            return value
    return raw

def clean_pilot_identity(name, country=""):
    """Normalise country and remove a recognised country suffix from a pilot name."""
    name = str(name or "").strip()
    country = normalise_country(country)
    if country and name.casefold().endswith(" " + country.casefold()):
        name = name[:-(len(country) + 1)].rstrip()
        return name, country
    # Also recover nationality from a name when an older import stored it there.
    for country_name in COUNTRY_NAMES:
        if name.casefold().endswith(" " + country_name.casefold()):
            name = name[:-(len(country_name) + 1)].rstrip()
            return name, normalise_country(country_name)
    return name, country
